function ensureOctrackerSchema(PDO $conn): void
{
    ensureUsersTable($conn);
    ensureStudentsTable($conn);
    ensureStudentRequirementsTable($conn);
    ensureSystemSettingsTable($conn);
    ensureActivityLogTable($conn);
    ensureLoginHistoryTable($conn);
}

/** Portable substitute for MySQL GROUP_CONCAT(... SEPARATOR ', '). */
function octrackerGroupConcat(string $expression, string $separator = ', ', ?PDO $conn = null): string
{
    if (octrackerIsPostgres($conn)) {
        $sep = str_replace("'", "''", $separator);
        return "STRING_AGG({$expression}::text, '{$sep}')";
    }
    $sep = str_replace("'", "''", $separator);
    return "GROUP_CONCAT({$expression} SEPARATOR '{$sep}')";
}

function octrackerGroupConcatDistinctOrdered(string $column, string $separator = ', ', ?PDO $conn = null): string
{
    if (octrackerIsPostgres($conn)) {
        $sep = str_replace("'", "''", $separator);
        return "STRING_AGG(DISTINCT {$column}::text, '{$sep}' ORDER BY {$column}::text)";
    }
    $sep = str_replace("'", "''", $separator);
    return "GROUP_CONCAT(DISTINCT {$column} ORDER BY {$column} SEPARATOR '{$sep}')";
}
