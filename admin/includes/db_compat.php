<?php

/**
 * MySQL + Postgres helpers for OCTRacker.
 */

function octrackerDbDriver(?PDO $conn = null): string
{
    if (isset($GLOBALS['octracker_db_driver']) && is_string($GLOBALS['octracker_db_driver'])) {
        return $GLOBALS['octracker_db_driver'];
    }
    if ($conn instanceof PDO) {
        return $conn->getAttribute(PDO::ATTR_DRIVER_NAME) ?: 'mysql';
    }
    return 'mysql';
}

function octrackerIsPostgres(?PDO $conn = null): bool
{
    return octrackerDbDriver($conn) === 'pgsql';
}

/** Strip MySQL backticks so the same SQL runs on Postgres. */
function octrackerSql(string $sql, ?PDO $conn = null): string
{
    if (octrackerIsPostgres($conn)) {
        return str_replace('`', '', $sql);
    }
    return $sql;
}

function octrackerTableExists(PDO $conn, string $table): bool
{
    if (octrackerIsPostgres($conn)) {
        $stmt = $conn->prepare(
            'SELECT 1 FROM information_schema.tables WHERE table_schema = current_schema() AND table_name = ? LIMIT 1'
        );
        $stmt->execute([$table]);
        return (bool) $stmt->fetchColumn();
    }

    $stmt = $conn->query('SHOW TABLES LIKE ' . $conn->quote($table));
    return $stmt !== false && (bool) $stmt->fetchColumn();
}

function octrackerColumnExists(PDO $conn, string $table, string $column): bool
{
    if (octrackerIsPostgres($conn)) {
        $stmt = $conn->prepare(
            'SELECT 1 FROM information_schema.columns WHERE table_schema = current_schema() AND table_name = ? AND column_name = ? LIMIT 1'
        );
        $stmt->execute([$table, $column]);
        return (bool) $stmt->fetchColumn();
    }

    $stmt = $conn->query('SHOW COLUMNS FROM `' . str_replace('`', '', $table) . '` LIKE ' . $conn->quote($column));
    return $stmt !== false && (bool) $stmt->fetchColumn();
}

/** @return list<string> */
function octrackerListColumns(PDO $conn, string $table): array
{
    if (octrackerIsPostgres($conn)) {
        $stmt = $conn->prepare(
            'SELECT column_name FROM information_schema.columns WHERE table_schema = current_schema() AND table_name = ? ORDER BY ordinal_position'
        );
        $stmt->execute([$table]);
        return array_map('strval', $stmt->fetchAll(PDO::FETCH_COLUMN));
    }

    $safe = str_replace('`', '', $table);
    return array_map('strval', $conn->query('SHOW COLUMNS FROM `' . $safe . '`')->fetchAll(PDO::FETCH_COLUMN));
}

function octrackerEnsureColumn(PDO $conn, string $table, string $column, string $mysqlDefinition, string $pgsqlDefinition = ''): void
{
    if (octrackerColumnExists($conn, $table, $column)) {
        return;
    }
    $def = octrackerIsPostgres($conn)
        ? ($pgsqlDefinition !== '' ? $pgsqlDefinition : $mysqlDefinition)
        : $mysqlDefinition;
    $conn->exec('ALTER TABLE ' . $table . ' ADD COLUMN ' . $column . ' ' . $def);
}

function octrackerPkColumn(PDO $conn): string
{
    return octrackerIsPostgres($conn)
        ? 'id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY'
        : 'id INT AUTO_INCREMENT PRIMARY KEY';
}

function ensureUsersTable(PDO $conn): void
{
    if (octrackerTableExists($conn, 'users')) {
        return;
    }
    $pk = octrackerPkColumn($conn);
    if (octrackerIsPostgres($conn)) {
        $conn->exec("CREATE TABLE users (
            {$pk},
            fullname VARCHAR(255) NOT NULL,
            username VARCHAR(100) NOT NULL UNIQUE,
            password VARCHAR(255) NOT NULL,
            role VARCHAR(50) NOT NULL
        )");
    } else {
        $conn->exec("CREATE TABLE users (
            {$pk},
            fullname VARCHAR(255) NOT NULL,
            username VARCHAR(100) NOT NULL,
            password VARCHAR(255) NOT NULL,
            role VARCHAR(50) NOT NULL,
            UNIQUE KEY username (username)
        )");
    }
}

function ensureStudentsTable(PDO $conn): void
{
    if (!octrackerTableExists($conn, 'students')) {
        $pk = octrackerPkColumn($conn);
        $conn->exec("CREATE TABLE students (
            {$pk},
            fullname VARCHAR(255) NULL,
            full_name VARCHAR(255) NULL,
            student_number VARCHAR(100) NULL,
            email VARCHAR(255) NULL,
            program VARCHAR(150) NULL,
            year_level VARCHAR(100) NULL,
            section VARCHAR(100) NULL,
            student_status VARCHAR(50) DEFAULT 'Regular',
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
            archived_at TIMESTAMP NULL
        )");
    }

    octrackerEnsureColumn($conn, 'students', 'fullname', 'VARCHAR(255) NULL');
    octrackerEnsureColumn($conn, 'students', 'full_name', 'VARCHAR(255) NULL');
    octrackerEnsureColumn($conn, 'students', 'student_number', 'VARCHAR(100) NULL');
    octrackerEnsureColumn($conn, 'students', 'email', 'VARCHAR(255) NULL');
    octrackerEnsureColumn($conn, 'students', 'program', 'VARCHAR(150) NULL');
    octrackerEnsureColumn($conn, 'students', 'year_level', 'VARCHAR(100) NULL');
    octrackerEnsureColumn($conn, 'students', 'section', 'VARCHAR(100) NULL');
    octrackerEnsureColumn($conn, 'students', 'student_status', "VARCHAR(50) DEFAULT 'Regular'");
    octrackerEnsureColumn($conn, 'students', 'created_at', 'TIMESTAMP DEFAULT CURRENT_TIMESTAMP');
    octrackerEnsureColumn($conn, 'students', 'archived_at', 'TIMESTAMP NULL', 'TIMESTAMP NULL');
}

function ensureStudentRequirementsTable(PDO $conn): void
{
    if (octrackerTableExists($conn, 'student_requirements')) {
        return;
    }
    $pk = octrackerPkColumn($conn);
    $conn->exec("CREATE TABLE student_requirements (
        {$pk},
        student_id INT NOT NULL,
        requirement_name VARCHAR(255) NOT NULL,
        status VARCHAR(30) NOT NULL DEFAULT 'missing'
    )");
    if (octrackerIsPostgres($conn)) {
        $conn->exec('CREATE INDEX IF NOT EXISTS student_requirements_student_id_idx ON student_requirements (student_id)');
        $conn->exec('CREATE INDEX IF NOT EXISTS student_requirements_status_idx ON student_requirements (status)');
    } else {
        try {
            $conn->exec('CREATE INDEX student_id ON student_requirements (student_id)');
        } catch (Throwable $e) {
            // ignore
        }
        try {
            $conn->exec('CREATE INDEX status ON student_requirements (status)');
        } catch (Throwable $e) {
            // ignore
        }
    }
}

function ensureSystemSettingsTable(PDO $conn): void
{
    if (!octrackerTableExists($conn, 'system_settings')) {
        $pk = octrackerPkColumn($conn);
        $conn->exec("CREATE TABLE system_settings (
            {$pk},
            school_name VARCHAR(255) NOT NULL DEFAULT '',
            system_name VARCHAR(255) NOT NULL DEFAULT '',
            motto VARCHAR(255) NOT NULL DEFAULT '',
            academic_year VARCHAR(20) NOT NULL DEFAULT '',
            semester VARCHAR(50) NOT NULL DEFAULT '',
            college_requirements TEXT NULL,
            shs_requirements TEXT NULL
        )");
        return;
    }

    octrackerEnsureColumn($conn, 'system_settings', 'college_requirements', 'TEXT NULL');
    octrackerEnsureColumn($conn, 'system_settings', 'shs_requirements', 'TEXT NULL');
}

function ensureActivityLogTable(PDO $conn): void
{
    if (octrackerTableExists($conn, 'activity_log')) {
