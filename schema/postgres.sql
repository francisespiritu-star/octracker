-- OCTRacker schema for Postgres / Supabase
-- Run in Supabase SQL Editor, or let tools/import_mysql_dump_to_pgsql.php create tables.

CREATE TABLE IF NOT EXISTS users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fullname VARCHAR(255) NOT NULL,
  username VARCHAR(100) NOT NULL UNIQUE,
  password VARCHAR(255) NOT NULL,
  role VARCHAR(50) NOT NULL
);

CREATE TABLE IF NOT EXISTS students (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fullname VARCHAR(255) NULL,
  full_name VARCHAR(255) NULL,
  student_number VARCHAR(100) NULL,
  email VARCHAR(255) NULL,
  program VARCHAR(150) NULL,
  year_level VARCHAR(100) NULL,
  section VARCHAR(100) NULL,
  student_status VARCHAR(50) DEFAULT 'Regular',
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  archived_at TIMESTAMP NULL
);

CREATE TABLE IF NOT EXISTS student_requirements (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id INT NOT NULL,
  requirement_name VARCHAR(255) NOT NULL,
  status VARCHAR(30) NOT NULL DEFAULT 'missing'
);
CREATE INDEX IF NOT EXISTS student_requirements_student_id_idx ON student_requirements (student_id);
CREATE INDEX IF NOT EXISTS student_requirements_status_idx ON student_requirements (status);

CREATE TABLE IF NOT EXISTS system_settings (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  school_name VARCHAR(255) NOT NULL DEFAULT '',
  system_name VARCHAR(255) NOT NULL DEFAULT '',
  motto VARCHAR(255) NOT NULL DEFAULT '',
  academic_year VARCHAR(20) NOT NULL DEFAULT '',
  semester VARCHAR(50) NOT NULL DEFAULT '',
  college_requirements TEXT NULL,
  shs_requirements TEXT NULL
);

CREATE TABLE IF NOT EXISTS activity_log (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_name VARCHAR(255) NOT NULL,
  actor_role VARCHAR(100) NOT NULL,
  action VARCHAR(255) NOT NULL,
  details TEXT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS login_history (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username VARCHAR(255) NOT NULL,
  role VARCHAR(100) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
